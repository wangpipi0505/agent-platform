CREATE SCHEMA IF NOT EXISTS model;
CREATE TABLE model.provider (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id varchar(128) NOT NULL, code varchar(64) NOT NULL, name varchar(128) NOT NULL,
 protocol varchar(32) NOT NULL DEFAULT 'OPENAI_COMPATIBLE', base_url text NOT NULL,
 trust_labels jsonb NOT NULL, secret_ref text, tail_hint varchar(12),
 status varchar(24) NOT NULL DEFAULT 'DISABLED' CHECK(status IN ('DISABLED','ENABLED','DEGRADED')),
 created_by varchar(128) NOT NULL, created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(), deleted boolean NOT NULL DEFAULT false,
 UNIQUE(tenant_id,code)
);
CREATE TABLE model.entry (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id varchar(128) NOT NULL,
 provider_id bigint NOT NULL REFERENCES model.provider(id),
 model_name varchar(128) NOT NULL, display_name varchar(128) NOT NULL,
 context_window integer NOT NULL CHECK(context_window>0), max_output_tokens integer NOT NULL CHECK(max_output_tokens>0),
 capabilities jsonb NOT NULL DEFAULT '[]', tokenizer_url text,
 status varchar(16) NOT NULL DEFAULT 'ENABLED' CHECK(status IN ('DISABLED','ENABLED')),
 created_by varchar(128) NOT NULL, created_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(tenant_id,provider_id,model_name)
);
CREATE TABLE model.call_log (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, tenant_id varchar(128) NOT NULL,
 principal_id varchar(128) NOT NULL, run_id varchar(80), attempt_id bigint,
 invocation_ref varchar(160) NOT NULL, send_seq integer NOT NULL DEFAULT 1,
 model_entry_id bigint NOT NULL REFERENCES model.entry(id), provider_id bigint NOT NULL,
 call_kind varchar(16) NOT NULL DEFAULT 'FORMAL',
 actual_endpoint text NOT NULL, request_snapshot jsonb NOT NULL,
 status varchar(24) NOT NULL DEFAULT 'SENDING', estimated_tokens integer NOT NULL,
 prompt_tokens integer, completion_tokens integer, total_tokens integer,
 duration_ms integer, error_code varchar(40), response_snapshot jsonb,
 created_at timestamptz NOT NULL DEFAULT now(), ended_at timestamptz,
 UNIQUE(tenant_id,invocation_ref,send_seq)
);
CREATE INDEX call_log_run ON model.call_log(tenant_id,run_id,created_at DESC);
CREATE INDEX call_log_stats ON model.call_log(tenant_id,model_entry_id,created_at DESC);
