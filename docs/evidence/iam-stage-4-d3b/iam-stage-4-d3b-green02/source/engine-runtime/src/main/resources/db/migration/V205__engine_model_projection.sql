CREATE TABLE engine.model_invocation (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 run_id bigint NOT NULL REFERENCES engine.run(id),
 node_instance_id bigint NOT NULL REFERENCES engine.node_instance(id),
 round_no int NOT NULL,
 kind varchar(16) NOT NULL CHECK(kind IN ('MAIN','SUMMARY')),
 source_request jsonb NOT NULL,
 final_request jsonb,
 response jsonb,
 status varchar(16) NOT NULL DEFAULT 'PREPARED',
 sdk_attempts int NOT NULL DEFAULT 0,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 UNIQUE(node_instance_id,round_no,kind)
);
