-- PLAT-15（方案 §4.15 / 契约 §14）：写操作两段（PREPARE/EXECUTE）的持久化行动计划与执行授权。
-- engine.action_plan 逐份保存引擎盖章后的 actionPlan：digest 是盖章后 plan 的 canonical SHA-256，
-- execute_key = sha256("EXECUTE:" + callId + ":" + digest)。execute_key 的唯一约束是
-- "同一份计划只有一条 EXECUTE 授权记录"的硬保证：同一调用重复 PREPARE 出相同内容 → 复用同一行；
-- 内容变化 → 新 digest → 新行，旧行保留审计。审批节点 approval_context 只保存引用（id/digest），
-- 计划权威在表。回滚：DROP TABLE engine.action_plan（审批节点引用列随 tool_call/node_instance
-- 的 approval_context jsonb 存量保存，降级后旧引用不再被解释，两段调用退回 SINGLE_STEP 语义）。
CREATE TABLE engine.action_plan (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,run_id bigint NOT NULL REFERENCES engine.run(id),call_id bigint NOT NULL REFERENCES engine.tool_call(id),node_instance_id bigint NOT NULL REFERENCES engine.node_instance(id),
 digest char(64) NOT NULL,plan jsonb NOT NULL,execute_key char(64) NOT NULL UNIQUE,risk varchar(16) NOT NULL DEFAULT 'STANDARD',
 status varchar(16) NOT NULL DEFAULT 'PREPARED' CHECK(status IN ('PREPARED','APPROVED','EXECUTED','EXECUTE_FAILED','REJECTED')),
 expires_at timestamptz NOT NULL,confirmed_by varchar(64),confirmed_at timestamptz,double_confirmed boolean,
 execute_granted_at timestamptz,executed_status varchar(16),result_digest char(64),created_at timestamptz DEFAULT now()
);
CREATE INDEX action_plan_call ON engine.action_plan(call_id);
COMMENT ON TABLE engine.action_plan IS
    'PLAT-15: stamped actionPlan per PREPARE (digest/executeKey unique); confirmed_by/confirmed_at/execute_granted_at/result_digest form the runId/actionPlanId/confirmBy/confirmAt/result audit trail';
