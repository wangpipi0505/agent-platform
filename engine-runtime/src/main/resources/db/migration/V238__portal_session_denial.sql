CREATE TABLE engine.portal_session_denial (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id text NOT NULL,
    principal_id text NOT NULL,
    app_code text NOT NULL,
    session_id text NOT NULL,
    reason text NOT NULL CHECK (reason IN ('SUBJECT_MISMATCH', 'APP_MISMATCH', 'SESSION_OUT_OF_SCOPE')),
    trace_id text,
    recorded_at timestamptz NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX portal_session_denial_tenant_time ON engine.portal_session_denial(tenant_id, recorded_at);
