-- ① task——任务受理事实（受理即钉住发布快照与 mode；状态机 13 值见主方案 §4.4）
CREATE TABLE IF NOT EXISTS engine.task (
  id                        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  public_id                 varchar(64)  NOT NULL UNIQUE,
  tenant_id                 varchar(64)  NOT NULL,
  principal_id              varchar(64)  NOT NULL,
  app_code                  varchar(64)  NOT NULL,
  config_release_id         varchar(64)  NOT NULL,
  config_digest             char(64)     NOT NULL,
  mode                      varchar(8)   NOT NULL,
  purpose                   varchar(16)  NOT NULL DEFAULT 'EXECUTE',
  goal                      text         NOT NULL,
  input_ref                 varchar(256) NOT NULL,
  input_digest              char(64)     NOT NULL,
  parent_task_id            bigint       NULL REFERENCES engine.task(id),
  role                      varchar(48)  NULL,
  session_id                varchar(64)  NULL REFERENCES engine.chat_session(public_id),
  session_cursor            int          NULL,
  selected_plan_revision_id bigint       NULL,
  state                     varchar(32)  NOT NULL,
  state_version             int          NOT NULL DEFAULT 1,
  budget                    jsonb        NOT NULL DEFAULT '{}'::jsonb,
  deadline                  timestamptz  NULL,
  cancel_requested_at       timestamptz  NULL,
  result_ref                varchar(256) NULL,
  result_digest             char(64)     NULL,
  request_id                varchar(128) NOT NULL,
  request_digest            char(64)     NOT NULL,
  tool_policy               jsonb        NULL,
  created_at                timestamptz  NOT NULL DEFAULT now(),
  updated_at                timestamptz  NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, principal_id, request_id)
);

