-- AP-S05：外部服务生命周期。
-- manifest 是唯一权威配置；运行态只记录本平台托管的进程，进程本身不可能跨重启存活。
-- 审计与业务库同事务边界（生命周期动作都是短事务），不依赖应用日志留存。
CREATE TABLE IF NOT EXISTS skill.service_manifest (
  tenant_id varchar(128) NOT NULL,
  code varchar(64) NOT NULL,
  name varchar(128) NOT NULL,
  command jsonb NOT NULL,
  work_dir text NOT NULL,
  port integer NOT NULL CHECK (port BETWEEN 1 AND 65535),
  health_path varchar(512) NOT NULL,
  startup_timeout_ms bigint NOT NULL CHECK (startup_timeout_ms BETWEEN 1000 AND 600000),
  stop_timeout_ms bigint NOT NULL CHECK (stop_timeout_ms BETWEEN 100 AND 60000),
  enabled boolean NOT NULL DEFAULT true,
  created_by varchar(128) NOT NULL,
  updated_by varchar(128) NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (tenant_id, code)
);

CREATE TABLE IF NOT EXISTS skill.service_runtime (
  tenant_id varchar(128) NOT NULL,
  code varchar(64) NOT NULL,
  state varchar(16) NOT NULL CHECK (state IN ('STARTING','READY','UNHEALTHY','STOPPED','FAILED')),
  pid bigint,
  owner varchar(160),
  started_at timestamptz,
  heartbeat_at timestamptz,
  last_error text,
  exit_code integer,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (tenant_id, code),
  FOREIGN KEY (tenant_id, code) REFERENCES skill.service_manifest(tenant_id, code) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS skill.service_audit (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id varchar(128) NOT NULL,
  actor varchar(128) NOT NULL,
  service_code varchar(64) NOT NULL,
  action varchar(32) NOT NULL,
  result varchar(16) NOT NULL CHECK (result IN ('SUCCESS','FAILED')),
  detail jsonb NOT NULL DEFAULT '{}',
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS service_audit_lookup
  ON skill.service_audit(tenant_id, service_code, created_at DESC);
